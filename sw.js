/* UAT Lab service worker: small first download, per-file updates.
   - Install downloads only CORE (a few hundred KB). Every other page/script is saved the first time it is opened, then works offline.
   - files.json (generated by build_web.py) lists a hash per file. On an update only files whose hash changed are dropped and downloaded again.
   - BUILD is stamped by build_web.py so the browser notices a new version; 'dev' locally, and a dev copy never serves from cache (so edits show at once). */
const C='uat-lab',BUILD='5632a6d2b1';
const CORE=['index.html','uatlab.html','brand.css','nav.js','analogy.js','coach.js','ds-mods.js','farm-mods.js','sqa-mods.js','sync.js','tickets.js','today.js','uatdash.js','phonehome.js','sheet.js','manifest.webmanifest','icon-192.png'];
const key=u=>{const x=new URL(u,location.href);x.search='';x.hash='';if(x.pathname.endsWith('/'))x.pathname+='index.html';return x.href};
async function getJSON(c,name){try{const m=await c.match(key(name));return m?await m.json():null}catch(e){return null}}
async function fetchPut(c,f){const r=await fetch(key(f),{cache:'reload'});if(r.ok)await c.put(key(f),r.clone());return r}
async function setup(){
  const c=await caches.open(C);let man=null;
  try{const r=await fetch('files.json',{cache:'no-store'});if(r.ok)man=await r.json()}catch(e){}
  if(!man)return;
  const old=await getJSON(c,'files.json');
  if(!old){for(const k of await c.keys())await c.delete(k)}
  else{for(const f of Object.keys(old))if(old[f]!==man[f])await c.delete(key(f))}
  await Promise.all(CORE.filter(f=>man[f]).map(async f=>{if(!(await c.match(key(f))))try{await fetchPut(c,f)}catch(e){}}));
  await c.put(key('files.json'),new Response(JSON.stringify(man)));
}
self.addEventListener('install',e=>{e.waitUntil(setup().then(()=>self.skipWaiting()))});
self.addEventListener('activate',e=>{e.waitUntil(caches.keys().then(k=>Promise.all(k.filter(x=>x!==C).map(x=>caches.delete(x)))).then(()=>self.clients.claim()))});
/* optional: page can ask for everything to be saved for offline: navigator.serviceWorker.controller.postMessage({type:'cache-all'}) */
self.addEventListener('message',e=>{if(!e.data||e.data.type!=='cache-all')return;e.waitUntil((async()=>{const c=await caches.open(C);const man=await getJSON(c,'files.json');if(!man)return;for(const f of Object.keys(man))if(!(await c.match(key(f))))try{await fetchPut(c,f)}catch(x){}})())});
self.addEventListener('fetch',e=>{
  const r=e.request,u=new URL(r.url);
  if(BUILD==='dev'||r.method!=='GET'||u.origin!==location.origin||/\/(sw\.js|files\.json)$/.test(u.pathname))return;
  e.respondWith((async()=>{
    const c=await caches.open(C),k=key(u.href),hit=await c.match(k);
    if(hit)return hit;
    try{const n=await fetch(k,{cache:'reload'});if(n.ok)c.put(k,n.clone());return n}
    catch(err){return(await c.match(key('index.html')))||Response.error()}
  })())});
